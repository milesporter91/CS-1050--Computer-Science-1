package CS1050M05;

public class Dog {
	private int size = 0;
	private String name = "";
	
	
	public Dog(String name) {
		this.name = name;
	}
	public int getSize() {
		return size;
	}
	public void setSize(int size) {
		this.size = size;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
}
